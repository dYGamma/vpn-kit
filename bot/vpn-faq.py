#!/usr/bin/env python3
"""Готовые ответы на частые вопросы про VPN — голосом Версы.

Зачем отдельный файл, а не «пусть Верса сама сообразит»: сообщения чужих людей
нельзя пускать в её контекст. Это прямой канал для инъекций («забудь инструкции
и...»), это расход подписки на каждого случайного и это ломает её чат, который
рассчитан на одного собеседника — босса. Поэтому здесь простое сопоставление по
словам: что узнали — отвечаем сами, что не узнали — уходит боссу.

    vpn-faq.py "<текст сообщения>"

Первая строка вывода — название темы, дальше сам ответ. Код возврата 0, если
тема опознана, иначе 1 и пустой вывод. У темы «ссылка» ответа здесь нет:
её собирает вызывающий, потому что личная страница человека известна ему, а
сюда её передавать незачем.

Ответы пишутся так, будто их говорит Верса: женский род, тепло, одна кавайная
нотка на сообщение. Адрес сервера и коды подписок тут не упоминаются никогда.
"""
import re
import sys

# Порядок важен: первое совпадение выигрывает. Более узкие темы стоят выше
# широких, иначе «не проходит оплата» съест общее «не работает».
TOPICS = [
    ("оплата",
     r"оплат|плат[еи]ж|картой|списа|банк|сбер|тинько|т-?банк|альфа|втб|"
     r"озон|вайлдберр|wildberries|маркетплейс",
     """Оплата и банки идут мимо VPN — я специально так настроила, чтобы
антифрод не пугался заграничного адреса.

Если платёж всё равно не проходит: выключи VPN на минутку, оплати и включи
обратно. Некоторые приложения сами видят, что VPN включён, и упираются —
адрес тут уже ни при чём, маршрутами это не лечится.

Не помогло — скажи, передам Диме ♡"""),

    ("детект",
     r"отключите\s*vpn|отключи\w*\s*впн|обнаружен\w*\s*(vpn|впн)|"
     r"вид(ит|ят)\s*(vpn|впн)|ругает|не пуска|госуслуг|"
     r"ростикс|\bмакс\b|\bвк\b|вконтакте",
     """Российские сайты у нас и так идут мимо VPN — они видят твой домашний
адрес, а не заграничный.

Но некоторые приложения (Госуслуги, Ростикс, МАКС) проверяют не адрес, а сам
факт включённого VPN прямо на телефоне. Их запросы до нашего сервера вообще
не доходят, и починить это с нашей стороны нельзя.

Лечится только так: выключить VPN на время, пока пользуешься именно этим
приложением. Всё остальное при этом работает как обычно."""),

    ("не работает",
     r"не работа|не подключ|не коннект|отвалил|обрыв|перестал|не грузит|"
     r"не открыва|ошибка подключ|таймаут|timeout|handshake|не соединя",
     """Попробуй переключиться на другой узел — в приложении их пять, и они
специально разные.

Порядок, который спасает чаще всего:
1. «Основной 443» или «Резерв 8443» — они по TCP и переживают почти любую сеть;
2. «Shadowsocks» — если и они молчат;
3. «Hysteria2» — самый быстрый, но у некоторых операторов режется.

Если ни один не поднялся — напиши, я передам Диме, он посмотрит по логам ♡"""),

    ("медленно",
     r"медлен|тормоз|\bлаг|пинг|ping|скорост|буфер|долго груз|подвисает",
     """Скорость сильно зависит от узла. Попробуй «Hysteria2» — он обычно
самый быстрый, у него отдельный протокол.

Если он у тебя не идёт, бери «Основной 443». А ещё в приложении есть
автовыбор — он сам меряет задержку и берёт живой узел."""),

    ("приложение",
     r"как(ое|ую)?\s*(приложен|прогр|клиент)|что (ставить|скачать|качать)|"
     r"установ|скачат|андроид|android|айфон|iphone|\bios\b|виндовс|windows|"
     r"на комп|на пк|макбук|macos|линукс|linux",
     """У тебя есть личная страница — там уже подобрано приложение под твою
систему и кнопка, которая настраивает всё в один клик.

Открой её, выбери свою систему и жми кнопку подключения. Ничего вручную
вбивать не нужно (≧▽≦)"""),

    ("обновить",
     r"обнов|не появ|мало (узл|профил|серверов)|только (три|3|два|2)|"
     r"пропал\w* (узл|сервер|профил)|нет (узл|сервер)",
     """Потяни список вниз или нажми «Обновить подписку» в приложении — узлы
подтягиваются оттуда, и после изменений их надо перечитать.

Если после обновления всё равно не то — скажи, что именно видишь, я передам
Диме ♡"""),

    ("ссылка",
     r"ссылк|потер|заново|где мо[яe]|скинь ещ|пришли ещ|не сохран|"
     r"забыл\w* адрес|куда заходить",
     ""),

    ("деньги",
     r"сколько стоит|цена|платн|бесплатн|подписка стоит|оплатить доступ|"
     r"сколько в месяц|донат",
     """Это личный VPN Димы, не сервис — денег за него не берут ♡
Просто пользуйся аккуратно и не раздавай доступ дальше."""),
]


def match(text):
    """Возвращает (тема, ответ) или (None, None). «ё» приводим к «е» с обеих
    сторон: люди пишут и так и так, а два набора шаблонов держать незачем."""
    t = (text or "").lower().replace("ё", "е")
    for name, pattern, answer in TOPICS:
        if re.search(pattern, t):
            return name, answer
    return None, None


if __name__ == "__main__":
    name, answer = match(sys.argv[1] if len(sys.argv) > 1 else "")
    if not name:
        sys.exit(1)
    print(name)
    if answer:
        print(answer)
    sys.exit(0)
